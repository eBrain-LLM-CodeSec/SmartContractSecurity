"""The first frozen RTF evaluation, against a real EVMbench target.

Target: 2023-07-pooltogether's Vault.sol -- chosen because it is the
ONLY audit in the corpus this project has real, frozen L11 correspondence
records for beyond the original Track A 6-requirement scope (see
rtf/l11_correspondence/L11_PROCESS_NOTES.md's extension section), and
because it is a fully self-contained repo (all vendored dependencies
present on disk) that compiles without needing forge (see AR-009).

This script:
1. Checks the freeze gate. Refuses to run if it does not pass.
2. Compiles the real target and runs every registered predicate
   (rtf.l12_evaluation.run_rtf).
3. Builds ground-truth findings from the frozen L11 correspondence
   mapping, with real locations extracted from the audit's own fix-patch
   diffs (not guessed).
4. Computes all 9 stage-separated metrics.
5. Writes a full, raw results artifact preserving every intermediate
   value (routed decisions, evidence, errors, metric inputs/outputs).

Usage:
    .venv/bin/python3 -m rtf.l12_evaluation.run_first_evaluation
"""
from __future__ import annotations

import json
import sys
from dataclasses import asdict
from pathlib import Path

from rtf.l12_evaluation.freeze_gate import DEFAULT_FROZEN_PATH, check_gate
from rtf.l12_evaluation.metrics import GroundTruthFinding
from rtf.l12_evaluation.run_rtf import build_context_for_evmbench_target, collect_tool_versions, load_unconditioned_map, run_rtf
from rtf.l12_evaluation import metrics as M

REPO_ROOT = Path(__file__).resolve().parents[2]

# Real, external target -- cloned fresh at the pinned base_commit per
# this project's own established reproduction recipe (CLAUDE.md /
# rtf/l11_correspondence/L11_PROCESS_NOTES.md). Not durable inside this
# repo (lives in job scratch space) -- the exact clone recipe is
# documented in AR-009's resolution and CLAUDE.md's Run 3 reproduction
# notes, so this path is a CONFIGURATION VALUE for this specific run,
# not something this script fetches itself.
POOLTOGETHER_VAULT_ROOT = Path("/scratch/md5344/.claude/jobs/318205ae/tmp/pooltogether_src/vault")
POOLTOGETHER_ENTRY = POOLTOGETHER_VAULT_ROOT / "src" / "Vault.sol"
POOLTOGETHER_SOLC_VERSION = "0.8.17"

# Ground truth locations, extracted directly from the real fix-patch
# diffs (patch/H-02.diff, patch/H-04.diff) -- NOT guessed, NOT inferred
# from the finding writeup's prose alone. `grep -n "^@@\|function "` on
# each diff shows the exact functions the fix touches.
GROUND_TRUTH_LOCATIONS = {
    "2023-07-pooltogether/H-02": ["Vault._mint", "Vault._burn", "Vault._transfer"],
    "2023-07-pooltogether/H-04": ["Vault.mintYieldFee"],
}

# A documented, known Slither limitation for this SPECIFIC target
# (confirmed during compilation -- see the ERROR:ContractSolcParsing log
# line every run of this target produces): TierCalculationLib.getTierOdds
# cannot have its IR generated by this Slither version. Not connected to
# any requirement's own predicate logic, but any predicate whose
# evidence-collection walks EVERY function in the compilation unit could
# in principle be affected for that one function. No requirement in the
# current registry is known to specifically depend on
# TierCalculationLib.getTierOdds, so this is recorded for completeness
# but not applied as a per-requirement PARSER_LIMITATION override.
KNOWN_LIMITATIONS: dict[str, str] = {}


def load_correspondence_for_audit(audit_id: str) -> list[GroundTruthFinding]:
    mapping_path = REPO_ROOT / "rtf" / "l11_correspondence" / "correspondence_mapping.json"
    records = json.loads(mapping_path.read_text(encoding="utf-8"))
    by_finding: dict[str, list[tuple[str, str]]] = {}
    for r in records:
        if not r["finding_id"].startswith(audit_id + "/"):
            continue
        by_finding.setdefault(r["finding_id"], []).append((r["req_id"], r["relationship"]))

    findings = []
    for finding_id, correspondences in by_finding.items():
        findings.append(GroundTruthFinding(
            finding_id=finding_id,
            audit_id=audit_id,
            correspondences=tuple(correspondences),
            ground_truth_locations=tuple(GROUND_TRUTH_LOCATIONS.get(finding_id, [])),
        ))
    return findings


def main() -> int:
    print("=== L12 first frozen evaluation ===")
    print(f"Target: 2023-07-pooltogether Vault.sol")
    print()

    print("--- Step 1: freeze gate ---")
    gate_result = check_gate(DEFAULT_FROZEN_PATH)
    print(gate_result.report())
    if not gate_result.passed:
        print()
        print("GATE FAILED -- refusing to proceed with evaluation.")
        return 1
    print()

    print("--- Step 2: compile + run RTF against the real target ---")
    ctx, compile_error = build_context_for_evmbench_target(POOLTOGETHER_ENTRY, POOLTOGETHER_VAULT_ROOT, POOLTOGETHER_SOLC_VERSION)
    if compile_error:
        print(f"COMPILATION FAILED: {compile_error}")
        return 1
    print(f"Compiled OK. {len(ctx.slither.contracts)} contracts, {len(ctx.sol_source_paths)} .sol files found.")

    unconditioned_map = load_unconditioned_map(REPO_ROOT / "rtf" / "l1_corpus" / "requirement_corpus.json")
    run, raw = run_rtf(ctx, "2023-07-pooltogether", unconditioned_map, KNOWN_LIMITATIONS)

    n_applicable = sum(1 for r in run.routed.values() if r.applicability_state.value == "APPLICABLE")
    n_crashed = sum(1 for r in raw.values() if r["operational_status"] != "OK")
    print(f"Evaluated {len(run.routed)} requirements: {n_applicable} APPLICABLE, {n_crashed} operational failures.")
    print()

    print("--- Step 3: load L11 ground truth for this audit ---")
    findings = load_correspondence_for_audit("2023-07-pooltogether")
    print(f"{len(findings)} real finding(s) with L11 correspondence records: {[f.finding_id for f in findings]}")
    for f in findings:
        direct = [rid for rid, rel in f.correspondences if rel == "DIRECT"]
        print(f"  {f.finding_id}: DIRECT -> {direct}, ground_truth_locations={list(f.ground_truth_locations)}")
    print()

    print("--- Step 4: compute stage-separated metrics ---")
    metric_results = {
        "requirement_routing_recall": M.requirement_routing_recall(run, findings),
        "requirement_routing_precision": M.requirement_routing_precision(run, findings),
        "target_localization_accuracy": M.target_localization_accuracy(run, findings),
        "evidence_collection_recall": M.evidence_collection_recall(run, findings),
        "final_finding_recall": M.final_finding_recall(run, findings),
        "false_alert_rate": M.false_alert_rate(run, findings),
        "inconclusive_rate": M.inconclusive_rate(run),
        "insufficient_evidence_rate": M.insufficient_evidence_rate(run),
        "applicability_recall_on_known_applicable": M.applicability_recall_on_known_applicable(run, findings),
    }
    for name, (num, den) in metric_results.items():
        pct = f"{100*num/den:.0f}%" if den else "n/a"
        print(f"  {name}: {num}/{den} ({pct})")
    print()

    print("--- Step 5: write full raw artifact ---")
    out_path = REPO_ROOT / "rtf" / "l12_evaluation" / "FIRST_EVALUATION_RESULT.json"
    artifact = {
        "run_metadata": {
            "audit_id": "2023-07-pooltogether",
            "target_entry_file": str(POOLTOGETHER_ENTRY),
            "solc_version": POOLTOGETHER_SOLC_VERSION,
            "tool_versions": collect_tool_versions(),
            "freeze_manifest": gate_result.frozen_manifest,
        },
        "ground_truth_findings": [asdict(f) for f in findings],
        "routed_results": raw,
        "metrics": {name: {"numerator": num, "denominator": den} for name, (num, den) in metric_results.items()},
        "confidence_caveat": (
            "L11 correspondence DIRECT records for this audit were built under a "
            "documented SUBSTANTIAL prior-exposure mitigation (fresh non-forked "
            "subagent, not true personnel separation) -- per the plan's own "
            "mandate, all recall-like metrics above computed from DIRECT records "
            "carry an explicit confidence downgrade. See "
            "rtf/l11_correspondence/L11_PROCESS_NOTES.md for the full disclosure."
        ),
    }
    out_path.write_text(json.dumps(artifact, indent=2, default=str), encoding="utf-8")
    print(f"Written -> {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
